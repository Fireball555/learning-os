"""Deterministic seed-data generator. Output: db/02_seed.sql.

Run: python db/generate_seed.py
Same seed -> byte-identical SQL, so expected result sets never drift.
"""
import random
from datetime import date, timedelta
from decimal import Decimal
from pathlib import Path

R = random.Random(20261109)

FIRST = ["Aarav", "Diya", "Karthik", "Meera", "Vikram", "Ananya", "Rohan", "Kavya", "Arjun", "Nila",
         "Siddharth", "Ishita", "Pranav", "Lakshmi", "Harish", "Divya", "Naveen", "Priya", "Surya", "Tara",
         "Gokul", "Revathi", "Ajay", "Sneha", "Bharath", "Keerthi", "Manoj", "Pooja", "Ravi", "Shruti",
         "Vignesh", "Aishwarya", "Dinesh", "Janani", "Kiran", "Monica", "Nikhil", "Oviya", "Pradeep", "Swathi",
         "Varun", "Yamini", "Ashwin", "Bhavana"]
LAST = ["Kumar", "Raman", "Iyer", "Nair", "Reddy", "Shankar", "Menon", "Pillai", "Rao", "Subramanian"]
CITIES = ["Coimbatore", "Chennai", "Salem", "Madurai", "Tiruppur", "Erode", "Bengaluru", "Kochi"]

CATEGORIES = ["Books", "Electronics", "Stationery", "Kitchen", "Sports", "Gardening"]  # Gardening: no products
PRODUCTS = {
    "Books": [("SQL Basics", 450), ("Data Stories", 620), ("Tamil Classics Vol 1", 380), ("Python Pocket Guide", 299),
              ("Startup Notes", 540)],
    "Electronics": [("USB-C Cable", 249), ("Wireless Mouse", 799), ("Bluetooth Speaker", 2499), ("Power Bank 10k", 1299),
                    ("Earbuds Lite", 1899), ("Webcam HD", 2199)],
    "Stationery": [("Gel Pen Pack", 120), ("A5 Notebook", 85), ("Highlighter Set", 150), ("Sticky Notes", 60),
                   ("Geometry Box", 210)],
    "Kitchen": [("Steel Tumbler", 180), ("Dosa Tawa", 899), ("Spice Box", 649), ("Water Bottle 1L", 349),
                ("Tea Strainer", 75)],
    "Sports": [("Cricket Ball", 199), ("Yoga Mat", 699), ("Skipping Rope", 149), ("Badminton Racket", 1199),
               ("Shuttlecock Tube", 399)],
}
DELIVERY_FEE = Decimal("40.00")
BOUNDARY = {7: date(2026, 3, 31), 13: date(2026, 1, 1), 21: date(2025, 12, 31), 29: date(2025, 12, 1),
            37: date(2025, 1, 1), 45: date(2026, 4, 1), 53: date(2025, 11, 30), 61: date(2024, 12, 31)}
NEVER_ORDERED ={"Startup Notes", "Webcam HD", "Geometry Box", "Tea Strainer"}  # anti-join targets


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, Decimal)):
        return str(v)
    if isinstance(v, date):
        return f"'{v.isoformat()}'"
    return "'" + str(v).replace("'", "''") + "'"


def rand_date(a: date, b: date) -> date:
    return a + timedelta(days=R.randint(0, (b - a).days))


def main():
    out = ["-- GENERATED by db/generate_seed.py — do not edit by hand", "BEGIN;"]

    # customers
    names = R.sample([f"{f} {l}" for f in FIRST for l in LAST], 44)
    customers = []
    for i, n in enumerate(names, start=1):
        customers.append((i, n, R.choice(CITIES), rand_date(date(2024, 6, 1), date(2026, 3, 31))))
    cust_at = len(out)   # customers are inserted here once their first order date is known
    no_order_customers = set(R.sample([c[0] for c in customers], 6))

    # categories / products
    for i, c in enumerate(CATEGORIES, start=1):
        out.append(f"INSERT INTO shop.categories VALUES ({i},{q(c)});")
    products, pid = [], 0
    for ci, c in enumerate(CATEGORIES, start=1):
        for name, price in PRODUCTS.get(c, []):
            pid += 1
            products.append((pid, name, ci, Decimal(price).quantize(Decimal("0.01"))))
    out += [f"INSERT INTO shop.products VALUES ({','.join(map(q, p))});" for p in products]
    orderable = [p for p in products if p[1] not in NEVER_ORDERED]

    # orders, items, payments
    active = [c for c in customers if c[0] not in no_order_customers]
    orders = {}
    for oid in range(1, 161):
        cust = R.choice(active)
        start = max(cust[3], date(2025, 1, 1))
        od = rand_date(start, date(2026, 6, 30))
        status = R.choices(["delivered", "shipped", "cancelled"], [70, 18, 12])[0]
        orders[oid] = [cust[0], od, status]
    # Guarantee rows exactly on range edges, owned by a customer with no other order
    # within 100 days, so an off-by-one date filter changes the result set.
    for oid, bd in BOUNDARY.items():
        for c in active:
            near = any(o[0] == c[0] and abs((o[1] - bd).days) <= 100 for k, o in orders.items() if k != oid)
            taken = any(orders[b][0] == c[0] for b in BOUNDARY if b != oid)
            if not near and not taken:
                orders[oid] = [c[0], bd, "delivered"]
                break
        else:
            raise SystemExit(f"no free customer for boundary order {oid}")
    # Guarantee customers who ordered but never paid (all cancelled) and who never got a delivery.
    boundary_custs = {orders[b][0] for b in BOUNDARY}
    with_orders = sorted({o[0] for o in orders.values()} - boundary_custs, reverse=True)
    for cid, forced in zip(with_orders[:3], ["cancelled", "cancelled", "shipped"]):
        for o in orders.values():
            if o[0] == cid:
                o[2] = forced
    first = {}
    for o in orders.values():
        first[o[0]] = min(first.get(o[0], o[1]), o[1])
    customers = [(cid, n, city, min(sd, first.get(cid, sd))) for cid, n, city, sd in customers]  # signup <= first order
    out[cust_at:cust_at] = [f"INSERT INTO shop.customers VALUES ({','.join(map(q, c))});" for c in customers]
    out += [f"INSERT INTO shop.orders VALUES ({oid},{o[0]},{q(o[1])},{q(o[2])});" for oid, o in orders.items()]

    pay_id = 0
    for oid, (_, od, status) in orders.items():
        total = Decimal("0")
        for p in R.sample(orderable, R.choices([1, 2, 3, 4], [35, 35, 20, 10])[0]):
            qty = R.choices([1, 2, 3, 5], [60, 25, 10, 5])[0]
            # unit_price = list price, sometimes discounted 10%
            up = p[3] if R.random() > 0.2 else (p[3] * Decimal("0.9")).quantize(Decimal("0.01"))
            total += up * qty
            out.append(f"INSERT INTO shop.order_items VALUES ({oid},{p[0]},{qty},{up});")
        if status != "cancelled":
            total += DELIVERY_FEE   # payments = item total + fee, so payments can't stand in for items
            parts = R.choices([1, 2, 3], [60, 30, 10])[0]
            remaining = total
            for k in range(parts):
                pay_id += 1
                amt = remaining if k == parts - 1 else (total / parts).quantize(Decimal("0.01"))
                remaining -= amt
                out.append(
                    f"INSERT INTO shop.payments VALUES ({pay_id},{oid},{amt},{q(R.choice(['upi', 'card', 'cod']))},"
                    f"{q(od + timedelta(days=k * 15))});")
    out.append("COMMIT;")
    Path(__file__).with_name("02_seed.sql").write_text("\n".join(out) + "\n")
    print(f"customers={len(customers)} products={len(products)} orders={len(orders)} payments={pay_id}")


if __name__ == "__main__":
    main()
